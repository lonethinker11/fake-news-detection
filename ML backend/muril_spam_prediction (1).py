from sentence_transformers import SentenceTransformer, util

semantic_model = SentenceTransformer(
    "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
)

# Filters out retrieved facts that do not share semantic meaning with the input claim
def filter_evidence(claim, evidence_list, threshold):
    filtered_evidence = []

    # Generate vector embedding for the target claim
    claim_embedding = semantic_model.encode(claim, convert_to_tensor=True)

    for evidence in evidence_list:
        # Generate embedding for each candidate evidence piece
        evidence_embedding = semantic_model.encode(
            evidence,
            convert_to_tensor=True
        )

        # Measure Cosine Similarity between claim and candidate
        similarity = util.cos_sim(
            claim_embedding,
            evidence_embedding
        ).item()

        # Only keep candidates above semantic relevancy limit
        if similarity >= threshold:
            filtered_evidence.append(evidence)

    return filtered_evidence

# Retrieve unique evidence articles using a threshold similarity of 0.70
